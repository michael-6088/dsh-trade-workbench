import { build } from "esbuild";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
mkdirSync(join(root, "lib"), { recursive: true });

await build({
  entryPoints: [join(root, "src/host/index.ts")],
  outfile: join(root, "lib/index.js"),
  bundle: true, format: "esm", platform: "node", target: "node22",
  external: ["@deepseek-ai/*"],
  banner: { js: "// dsh-trade-workbench host half — generated by scripts/build.mjs" },
  logLevel: "warning",
});

await build({
  entryPoints: [join(root, "src/client/index.ts")],
  outfile: join(root, "lib/.client.raw.js"),
  bundle: true, format: "cjs", platform: "browser",
  target: ["chrome120", "safari16"],
  jsx: "automatic",
  external: ["react", "react/jsx-runtime"],
  define: { __PLUGIN_VERSION__: JSON.stringify(pkg.version) },
  logLevel: "warning",
});

// DSH 模块加载器只向 factory 传 require：模块对象由 factory 自建（与官方包产出一致）
const raw = readFileSync(join(root, "lib/.client.raw.js"), "utf8").replace(/\r/g, "");
const shell = [
  "window.__ModuleLoader__.load({",
  "  id: " + JSON.stringify(pkg.name) + ",",
  "  factory: (require) => {",
  "    var module = { exports: {} };",
  "    var exports = module.exports;",
  "    Object.defineProperty(exports, Symbol.toStringTag, { value: \"Module\" });",
  raw,
  "    return module.exports;",
  "  },",
  "});",
].join("\n");
writeFileSync(join(root, "lib/client.js"), shell);

if (/require\(["']@deepseek-ai/.test(shell)) throw new Error("client bundle 含非法宿主 require");
console.log("build ok: lib/index.js + lib/client.js (" + Math.round(shell.length / 1024) + " KB)");